#!/usr/bin/env python3
"""Make an nv-sflow 0.2.1 batch wrapper preserve the workflow exit code."""

from __future__ import annotations

import argparse
import re
from pathlib import Path


SFLOW_RUN_RE = re.compile(r"^(?:\S*/)?sflow\s+run(?:\s|$)")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("script", type=Path, help="Script generated by `sflow batch -o`")
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    script = args.script
    source = script.read_text(encoding="utf-8")
    lines = source.splitlines()

    run_lines = [index for index, line in enumerate(lines) if SFLOW_RUN_RE.match(line)]
    if len(run_lines) != 1:
        raise RuntimeError(
            f"expected exactly one sflow run command in {script}, found {len(run_lines)}"
        )

    run_index = run_lines[0]
    if run_index + 1 >= len(lines) or lines[run_index + 1] != "SFLOW_RC=$?":
        lines.insert(run_index + 1, "SFLOW_RC=$?")

    if not any(line == 'exit "$SFLOW_RC"' for line in lines):
        lines.extend(["", 'exit "$SFLOW_RC"'])

    updated = "\n".join(lines) + "\n"
    if updated == source:
        print(f"PASS: {script} already preserves the sflow exit code")
        return 0

    script.write_text(updated, encoding="utf-8")
    print(f"UPDATED: {script} now preserves the sflow exit code")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
